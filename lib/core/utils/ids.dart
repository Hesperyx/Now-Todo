import 'package:uuid/uuid.dart';

const Uuid _uuid = Uuid();

/// 生成一个 v4 UUID 作为主键。
///
/// 主键在**客户端**生成，而不是让数据库自增。理由：
///
/// - 导入 JSON 时不会与本地已有记录撞号，合并逻辑因此简单得多；
/// - 将来若加入「导出后到别处编辑再导回」，对象身份仍然稳定；
/// - 删除后新增不会复用旧 id。
///
/// 代价是主键占 36 字节文本而非 8 字节整数。对这个量级的本地待办数据
/// （几千条）完全可以忽略。
String newId() => _uuid.v4();
